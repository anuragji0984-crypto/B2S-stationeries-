-- B2S LIVE SETUP
-- Run this once in Supabase SQL Editor.

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_code text unique not null,
  created_at timestamptz not null default now(),
  name text not null,
  phone text not null,
  address text,
  items text not null,
  mode text not null check (mode in ('Delivery','Pickup')),
  payment text not null,
  status text not null default 'Pending'
    check (status in ('Pending','Confirmed','Ready','Delivered','Rejected'))
);

alter table public.orders enable row level security;

-- Customers can submit orders without logging in.
drop policy if exists "public can insert orders" on public.orders;
create policy "public can insert orders"
on public.orders for insert
to anon, authenticated
with check (true);

-- Only authenticated admin users can read/update/delete orders.
drop policy if exists "admins can read orders" on public.orders;
create policy "admins can read orders"
on public.orders for select
to authenticated
using (true);

drop policy if exists "admins can update orders" on public.orders;
create policy "admins can update orders"
on public.orders for update
to authenticated
using (true)
with check (true);

drop policy if exists "admins can delete orders" on public.orders;
create policy "admins can delete orders"
on public.orders for delete
to authenticated
using (true);

-- Photo bucket.
insert into storage.buckets (id, name, public)
values ('order-photos', 'order-photos', false)
on conflict (id) do nothing;

alter table storage.objects enable row level security;

-- Customers can upload photos into the order-photos bucket.
drop policy if exists "public can upload order photos" on storage.objects;
create policy "public can upload order photos"
on storage.objects for insert
to anon, authenticated
with check (bucket_id = 'order-photos');

-- Only logged-in admins can read/delete photos.
drop policy if exists "admins can read order photos" on storage.objects;
create policy "admins can read order photos"
on storage.objects for select
to authenticated
using (bucket_id = 'order-photos');

drop policy if exists "admins can delete order photos" on storage.objects;
create policy "admins can delete order photos"
on storage.objects for delete
to authenticated
using (bucket_id = 'order-photos');
